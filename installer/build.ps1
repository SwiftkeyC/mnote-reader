<#
.SYNOPSIS
  Builds the Windows downloads for the website into docs\downloads.

.DESCRIPTION
    Mnote-Setup-x64.exe   installer for 64-bit Windows (most PCs; also Windows 11 on ARM)
    Mnote-Setup-x86.exe   installer for 32-bit Windows (also Windows 10 on ARM)
    Mnote-portable.zip    the app without an installer: unzip it, then use the .cmd files
    SHA256SUMS.txt        checksums of those three files
    release.json          the version, date, sizes and checksums, shown on the website

  The installers are compiled from setup.cs with the C# compiler that comes with Windows
  (.NET Framework 4), so nothing has to be installed to build them. Mnote itself is
  PowerShell and HTML, and is the same in every download.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\installer\build.ps1 -Version 1.0.1
#>
param([string]$Version = '1.0.0')

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem, System.Drawing
if ($Version -notmatch '^\d+\.\d+\.\d+$') { throw "The version must look like 1.2.3, not '$Version'." }

$root = Split-Path $PSScriptRoot
$out = Join-Path $root 'docs\downloads'
$tmp = Join-Path ([IO.Path]::GetTempPath()) ('mnote-build-' + [Guid]::NewGuid().ToString('N').Substring(0, 8))
[void][IO.Directory]::CreateDirectory($out)
[void][IO.Directory]::CreateDirectory($tmp)
$csc = Join-Path $env:windir 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not [IO.File]::Exists($csc)) { $csc = Join-Path $env:windir 'Microsoft.NET\Framework\v4.0.30319\csc.exe' }

# What the installer puts in %LOCALAPPDATA%\Programs\Mnote, and what the portable ZIP holds.
$appFiles = 'mnote.ps1', 'mnote-reader.html', 'Export OneNote.cmd', 'README.md', 'LICENSE'
$portableFiles = $appFiles + 'Install Mnote Reader.cmd', 'Uninstall Mnote Reader.cmd'

function New-Zip([string]$file, [string[]]$names, [string]$prefix) {
    if ([IO.File]::Exists($file)) { [IO.File]::Delete($file) }
    $zip = [IO.Compression.ZipFile]::Open($file, 'Create')
    try {
        foreach ($n in $names) {
            [void][IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, (Join-Path $root $n), $prefix + $n, 'Optimal')
        }
    }
    finally { $zip.Dispose() }
}

try {
    # The app icon, drawn by the same code that "mnote.ps1 install" uses.
    $ast = [Management.Automation.Language.Parser]::ParseFile((Join-Path $root 'mnote.ps1'), [ref]$null, [ref]$null)
    foreach ($name in 'New-RoundRect', 'New-MnoteIcon') {
        $fn = $ast.Find({ param($a) $a -is [Management.Automation.Language.FunctionDefinitionAst] -and $a.Name -eq $name }, $true)
        . ([scriptblock]::Create($fn.Extent.Text))
    }
    $ico = Join-Path $tmp 'mnote.ico'
    New-MnoteIcon $ico

    # The icon's 256-pixel image (stored in it as a PNG), for the setup window.
    $png = Join-Path $tmp 'logo.png'
    $b = [IO.File]::ReadAllBytes($ico)
    for ($i = 0; $i -lt [BitConverter]::ToUInt16($b, 4); $i++) {
        $e = 6 + 16 * $i
        if ($b[$e] -eq 0) {
            $img = New-Object byte[] ([BitConverter]::ToInt32($b, $e + 8))
            [Array]::Copy($b, [BitConverter]::ToInt32($b, $e + 12), $img, 0, $img.Length)
            [IO.File]::WriteAllBytes($png, $img)
        }
    }

    $payload = Join-Path $tmp 'payload.zip'
    New-Zip $payload $appFiles ''

    foreach ($arch in 'x64', 'x86') {
        $info = Join-Path $tmp "BuildInfo-$arch.cs"
        [IO.File]::WriteAllText($info, "// Generated by build.ps1.`r`nstatic class BuildInfo`r`n{`r`n    public const string Version = `"$Version`";`r`n    public const string Arch = `"$arch`";`r`n}`r`n")
        $exe = Join-Path $out "Mnote-Setup-$arch.exe"
        $log = & $csc /nologo /target:winexe "/platform:$arch" /optimize+ "/out:$exe" "/win32icon:$ico" "/win32manifest:$(Join-Path $PSScriptRoot 'setup.manifest')" "/resource:$payload,payload.zip" "/resource:$png,logo.png" /r:System.dll /r:System.Drawing.dll /r:System.Windows.Forms.dll /r:System.IO.Compression.dll /r:System.IO.Compression.FileSystem.dll (Join-Path $PSScriptRoot 'setup.cs') $info 2>&1
        if ($LASTEXITCODE -ne 0) { $log | Out-String | Write-Host; throw "The C# compiler failed for $arch." }
    }
    New-Zip (Join-Path $out 'Mnote-portable.zip') $portableFiles 'Mnote/'

    $files = [ordered]@{}
    $sums = foreach ($n in 'Mnote-Setup-x64.exe', 'Mnote-Setup-x86.exe', 'Mnote-portable.zip') {
        $f = Join-Path $out $n
        $hash = (Get-FileHash -Algorithm SHA256 -LiteralPath $f).Hash.ToLowerInvariant()
        $files[$n] = [ordered]@{ size = (Get-Item -LiteralPath $f).Length; sha256 = $hash }
        "$hash  $n"
    }
    $utf8 = New-Object Text.UTF8Encoding($false)
    [IO.File]::WriteAllText((Join-Path $out 'SHA256SUMS.txt'), (($sums -join "`n") + "`n"), $utf8)
    $release = [ordered]@{ version = $Version; date = (Get-Date).ToString('yyyy-MM-dd'); files = $files }
    [IO.File]::WriteAllText((Join-Path $out 'release.json'), ($release | ConvertTo-Json -Depth 4), $utf8)

    Write-Host "Built Mnote $Version in $out"
    foreach ($n in $files.Keys) { Write-Host ('  {0,-21} {1,4:N0} KB  {2}' -f $n, ($files[$n].size / 1KB), $files[$n].sha256) }
}
finally { [IO.Directory]::Delete($tmp, $true) }
